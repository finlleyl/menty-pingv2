"""Проверка черновиков и пингов кодом: созвоны вне регламента и «нейронистые» штампы.

Промпт модель иногда нарушает, а тексты уходят с аккаунта ментора — поэтому ловим
регулярками по основам слов. Модуль чистый (без IO), им пользуются и stages, и service.
"""
import re

# Предложение созвона — по основам слов. Это единственный источник: им же проверяется
# запретная тема «созвоны» в пингах (stages._FORBIDDEN_RE). Работает по тексту в нижнем регистре.
# Компромиссы против ложных срабатываний:
# - «звон» только с приставками со-/по-/пере-/до- или в начале слова: «позвоночник» отсечён,
#   «звонкий» ловится — в переписке ментора это слово почти не встречается;
# - «звонит/позвонят/звонил/созвонились» — третье лицо и прошедшее время: «рекрутеры звонят?»,
#   «если позвонят из Озона» — это не предложение созвона, а пинг на «Рынке» спрашивает такое законно;
# - «встреч» только в формах «встреча/встречу/встрече/встречаться/встречаемся»: «встречается
#   в уроке» (= попадается) и «встретил эту ошибку» не ловятся, «при встрече» — ловится;
# - «зум» без «зумеров»; «колл» отдельным словом, чтобы не ловить «коллегу» и «коллекцию»;
# - английский «call» — только отдельным словом и не «call stack», «function call», «метод call»,
#   «.Call(»: иначе технический ответ про Go постоянно считался бы предложением созвона;
# - «набрать» — только с «мне/меня/тебе/тебя» или «наберу»: «набери go env» — это терминал;
# - «по видео» — с глаголом разговора или в конце фразы: «по видео из урока» — это лекция;
# - повторный мок и «пробный собес» — тоже созвон с ментором, но голое «мок» — это и mock-объект
#   из тестов, поэтому ловим только формы предложения («ещё один мок», «прогоним мок»);
# - «созвон с HR», «звонок от рекрутера» — это собес ученика, а не созвон с ментором: на стадиях
#   «Собесы» и «Рынок» о них спрашивают законно. \b после слова не даёт обойти это исключение,
#   откусив окончание («созвоном с HR» не превращается в совпадение «созвоно»). Названия компаний
#   («созвон с Яндексом») регуляркой не отличить — промпт просит называть такое «собес».
CALL_PATTERN = (
    r"(?:\b(?:со|по|пере|до)?звон(?!оч)(?!(?:ит|ят|ил|ила|или|ило|ился|илась|ились)\b)\w*"
    r"|видео-?(?:звон|связ|конфер|встреч|чат)\w*"
    r"|\bзум(?!ер)\w*|\bzoom|\bmeet|\bмит|телемост\w*|discord\w*|дискорд\w*|скайп\w*|skype\w*"
    r"|\bголосом|\bголосов(?:ой|ую)|\bвойс\w*|\bвживую"
    r"|\bнаберу|\bнабер\w*\s+(?:мне|меня|тебе|тебя)|\b(?:мне|меня|тебе|тебя)\s+набер\w*"
    r"|(?:расшар|пошар|демонстр)\w*\s+экран\w*"
    r"|(?:обсуд|разбер|поговор|покаж)\w*\s+по\s+видео|\bпо\s+видео(?=[ \t]*(?:[.,!?)\n]|$))"
    r"|\bвстрет(?:имся|иться|ишься)|\bвстреч(?:а|у|е|аться|аемся)"
    r"|(?:ещё|еще)\s+(?:один|раз)\s+мок|повторн\w*\s+мок|прогон\w*\s+(?:\w+\s+){0,2}мок"
    r"|пробн\w*\s+(?:собес|интервью)\w*|(?:собес|интервью)\w*\s+со\s+мной"
    r"|потренир\w*\s+(?:вместе|со\s+мной)"
    r"|(?<![.\w])(?<!function )(?<!method )(?<!метод )(?<!метода )call(?![(\w])(?!\s+stack)"
    r"|\bколл(?:а|у|ом|е|ы|ов)?)\b"
    r"(?!\s+(?:со?|от|из)\s+(?:hr|эйчар|рекрутер|тимлид|техлид|компани|работодател|интервьюер))"
)
_CALL_RE = re.compile(CALL_PATTERN, re.IGNORECASE)

# Код в черновике проверять не нужно: `wg.Wait()` или ```reflect.Value.Call``` — не созвон
_CODE_RE = re.compile(r"```.*?```|`[^`\n]*`", re.DOTALL)

# Пометки ментору внутри черновика: «[по этому в материалах нет - допиши сам]», «[срок - допиши
# сам]», «[просит созвон - реши сам]». Это не текст для ученика: «Отправить» с ними не сработает,
# а проверки на созвон и штампы их не видят — «[просит созвон…]» не нарушение, а вопрос ментору
_MARK_RE = re.compile(r"\[[^\[\]\n]*\b(?:допиши|реши)\s+сам\b[^\[\]\n]*\]", re.IGNORECASE)


def todo_marks(text: str) -> list[str]:
    """Пометки «… допиши сам]» / «… реши сам]», оставленные моделью ментору."""
    return _MARK_RE.findall(text or "")


def _prose(text: str) -> str:
    return _MARK_RE.sub(" ", _CODE_RE.sub(" ", text or ""))


def call_hits(text: str) -> list[str]:
    """Фрагменты, похожие на предложение созвона/встречи. Пусто — созвона нет."""
    out: list[str] = []
    for m in _CALL_RE.finditer(_prose(text).lower()):
        if m.group(0) not in out:
            out.append(m.group(0))
    return out


# Типовые приметы текста от нейросети: (что показать ментору и в «перепиши без»; регулярка)
_TELLS = [
    ("«отличный вопрос»", r"(?:отличн|хорош|классн|прекрасн|интересн)\w*\s+вопрос"),
    ("«понимаю, как тебе непросто»",
     r"понимаю,?\s+(?:как|что)\s+тебе|понимаю\s+тво\w*\s+(?:чувств|пережив|эмоци|состояни)"),
    ("«я тебя слышу»", r"я\s+тебя\s+слышу|слышу\s+тебя"),
    ("«не переживай»", r"не\s+переживай"),
    ("«молодец, что поделился»",
     r"(?:молодец|спасибо),?\s+что\s+(?:поделил|рассказал|открыл|написал)"),
    ("«важно помнить»", r"важно\s+(?:помнить|отметить|понимать|подчеркнуть)"),
    ("«надеюсь, это поможет»", r"надеюсь,?\s+(?:это|мой\s+ответ|что\s+это)\s+(?:тебе\s+)?помо"),
    # «обращайся к полю через указатель» — техника, не штамп: ловим только прощальное «обращайся»
    ("«не стесняйся/обращайся»",
     r"не\s+стесняйся|\bобращайся\b(?=\s*(?:[.!)]|$|,?\s*(?:если|когда|в\s+любое)))"),
    ("«рад помочь»", r"\bрад(?:а)?\s+(?:помочь|был\w*\s+помочь)"),
    ("«давай разберёмся»", r"давай\s+разбер[её]мся"),
    # самые частые штампы именно в утешениях и поздравлениях — ради них проверка и затевалась
    ("«ты справишься»",
     r"ты\s+(?:обязательно\s+|точно\s+|вс[её]\s+)?справишься|не\s+сдавайся|на\s+правильном\s+пути"
     r"|\bты\s+не\s+один(?:ок|ока)?\b(?!\s+такой)"),
    ("«абсолютно нормально»", r"(?:абсолютно|совершенно)\s+нормально"),
    # «код отлично работает» — не штамп, поэтому только «отличная работа» целиком
    ("«отличная работа»",
     r"отличн(?:ая|ую)\s+работ|проделал\w*\s+(?:огромн|больш|отличн|хорош)\w*\s+работ"
     r"|так\s+держать|горжусь\s+тобой"),
    # «не понимаю тебя, что за ошибка?» — вопрос, а не сочувствие
    ("«понимаю тебя»", r"(?<!не )\bпонимаю\s+тебя\b|(?:^|[.!?]\s*)понимаю\s*[.!]"),
    ("канцелярит",
     r"\bданн(?:ый|ая|ое|ого|ой|ому|ом|ую)\s+(?:вопрос|тем|момент|этап|случа|ситуаци)"
     r"|в\s+рамках|осуществ\w+|следует\s+отметить"),
    ("отзеркаливание чувств, как у психолога",
     r"звучит\s+(?:так,?\s+)?(?:будто|как\s+будто)"
     r"|(?:похоже|кажется),?\s+(?:ты\s+чувству|тебе\s+сейчас\s+(?:тяжело|непросто|сложно))"
     r"|(?:это\s+)?(?:абсолютно\s+|совершенно\s+|вполне\s+)?нормально\s+(?:чувствовать|испытывать)"
     r"|твои\s+чувства"),
    ("markdown: **жирный**", r"\*\*[^*\n]+\*\*|__[^_\n]+__"),
    ("markdown: заголовки", r"(?m)^\s{0,3}#{1,6}\s"),
]
_TELL_RES = [(label, re.compile(rx, re.IGNORECASE)) for label, rx in _TELLS]

_BULLET_RE = re.compile(r"(?m)^\s*(?:[-*•]|\d+[.)])\s+\S")
_EMOJI_RE = re.compile("[\U0001F300-\U0001FAFF☀-➿⭐✅]")
# «!=» в Go-коде без бэктиков — не восклицание
_EXCL_RE = re.compile(r"!+(?!=)")

# Технические ответы могут законно содержать списки и шаги — для них списки не штамп
TECH_KINDS = ("tech_question", "org_question")


def ai_tells(text: str, kinds=(), ongoing: bool = False, samples=()) -> list[str]:
    """Приметы «нейронистого» текста. kinds — метки сортировщика; ongoing — диалог уже идёт;
    samples — настоящие сообщения ментора: его собственную манеру штампом не считаем."""
    prose = _prose(text)
    samples = list(samples or [])
    out = [label for label, rx in _TELL_RES if rx.search(prose)]
    technical = any(k in TECH_KINDS for k in kinds)
    if not technical and len(_BULLET_RE.findall(prose)) >= 2:
        out.append("markdown: список")
    # ментор сам ставит пару эмодзи или «Красава! Поздравляю!» — копировать это и просили
    if (len(_EMOJI_RE.findall(prose)) >= 3
            and not any(len(_EMOJI_RE.findall(s)) >= 2 for s in samples)):
        out.append("эмодзи пачкой")
    # «!!!» — одна эмоция, а три восклицательных предложения подряд — пересластил
    if (len(_EXCL_RE.findall(prose)) >= 3
            and not any(len(_EXCL_RE.findall(s)) >= 2 for s in samples)):
        out.append("три восклицания: «Молодец! Так держать! Всё получится!»")
    if ongoing and re.match(r"\s*привет\b", prose, re.IGNORECASE):
        out.append("«Привет!» посреди идущего диалога")
    return out


_DASH_RE = re.compile(r"(^|\s)[—–](?=\s)", re.MULTILINE)


def normalize_dashes(text: str, samples) -> str:
    """Длинное тире в русском тексте — главная примета нейросети: ментор с телефона ставит «-».

    Меняем, только если есть образцы ментора и ни в одном нет «—»: без образцов не знаем,
    как он пишет, и текст не трогаем."""
    samples = list(samples or [])
    if not samples or any("—" in s for s in samples):
        return text
    return _DASH_RE.sub(r"\1-", text)


def draft_problems(text: str, kinds, call: str | None, ongoing: bool = False,
                   samples=()) -> list[str]:
    """Что не так с черновиком ответа: созвон вне регламента и штампы. Пусто — всё чисто."""
    problems = []
    if call is None:
        hits = call_hits(text)
        if hits:
            # «упоминает», а не «предлагает»: отказ («созвоны у меня только после спринта»)
            # регулярка от предложения не отличит, а решать про созвон вне регламента ментору
            problems.append(f"упоминает созвон ({', '.join('«' + h + '»' for h in hits[:3])})")
    return problems + ai_tells(text, kinds, ongoing, samples)
