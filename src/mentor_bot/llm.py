Kind = Literal["tech_question", "org_question", "feelings", "win", "status_change", "smalltalk"]


class Triage(BaseModel):
    kinds: list[Kind]
    needs_reply: bool
    urgent: bool               # хочет бросить, тяжёлое выгорание, паника, беда в жизни
    milestone: Literal["none", "sprint_finished", "legend_ready"]


class StatusUpdate(BaseModel):
    new_status: str | None
    confidence: Literal["high", "low"]


class PlainText(BaseModel):
    text: str


class InterviewItem(BaseModel):
    company: str | None
    stage: str | None          # «HR», «техничка», «лайвкодинг», «финал» — как назвал ученик
    question: str              # сам вопрос или задача, коротко
    failed: bool               # ученик сказал, что не ответил, поплыл, срезался


class InterviewReport(BaseModel):
    items: list[InterviewItem]


