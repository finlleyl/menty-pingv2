    async def gen_ping(self, display, status, recent, profile, notes=None, avoid=None,
                       samples=None) -> str:
        stage = parse_stage(status)
        allowed, forbidden = ping_topics(stage)
        user = (
            f"Заметки ментора: {notes or 'нет'}\n"
            f"Досье: {profile or 'нет'}\n"
            f"Последняя переписка:\n{_dialog(recent) or 'нет'}\n"
            f"Ученик: {display}"
        )
        if samples:
            user += "\n\n" + _samples(samples)
        if avoid:
            user += _avoid(avoid)
        out: PlainText = await self._parse(
            self.smart,
            PING_SYS.format(
                stage_label=STAGE_LABELS[stage],
                allowed="; ".join(allowed),
                forbidden="; ".join(forbidden),
                # только там, где собесы — тема пинга: на спринтах само слово подтолкнуло бы к ним
                company_calls=COMPANY_CALLS if stage in ("interviews", "market") else "",
            ),
            user,
            PlainText,
            "ping",
        )
        return out.text

    async def draft_reply(self, text, kinds, *, recent=None, stage_label=None, status=None,
                          notes=None, profile=None, chunks=None, similar=None, examples=None,
                          samples=None, call=None, urgent=False, ongoing=False,
                          avoid=None) -> str:
        """Один черновик на всё новое от ученика: вопросы, переживания, успехи.

        chunks=None — вопросов нет: материалы курса не искали и в промпт не кладём вовсе.
        call — какой созвон разрешён в этом ответе по регламенту ("sprint", "mock",
        "mock_stage" или None); решает код, а не модель."""
        system = DRAFT_SYS.format(
            urgent=URGENT_RULE if urgent else "",
            call_rule=CALL_RULES[call],
            ongoing="Диалог уже идёт: не начинай с «Привет».\n" if ongoing else "",
        )
        user = (
            f"Новые сообщения ученика:\n{text}\n\n"
            f"Что в них: {', '.join(KIND_LABELS.get(k, k) for k in kinds)}\n"
            f"Этап ученика: {stage_label or 'неизвестен'} (статус в таблице: «{status or 'нет'}»)\n"
            f"Заметки ментора об ученике: {notes or 'нет'}\n"
            f"Досье: {profile or 'нет'}\n\n"
            f"Последняя переписка:\n{_dialog(recent or []) or 'нет'}"
        )
        if chunks is None:
            # сортировщик мог не заметить неявный вопрос («чувствую себя тупым, не понимаю
            # каналы» → одни переживания) — затык тогда не игнорируем, а просим подробности
            user += ("\n\nМатериалы не подбирались: техники и ссылок на уроки не вставляй. "
                     "Если видишь затык по теме, попроси прислать код или что именно непонятно.")
        else:
            # поиск всегда возвращает топ-5, даже если по теме ничего нет
            ctx = "\n\n---\n\n".join(_chunk_text(c) for c in chunks) or "(материалы не найдены)"
            user += ("\n\nВыдержки из материалов курса (их нашёл поиск, не все по теме: факты бери "
                     f"только из относящихся к вопросу, на остальные не ссылайся):\n{ctx}")
        if similar:
            user += ("\n\nПохожие прошлые сообщения учеников и что им ответил ментор (бери подход "
                     "и факты, имена и обстоятельства не переноси):\n") + "\n\n".join(
                f"Ученик: {s['question'][:500]}\nОтвет ментора: {s['final'][:800]}" for s in similar
            )
        if examples:
            user += "\n\nКак ментор переписывал прошлые черновики:\n" + "\n\n".join(
                f"Черновик: {e['draft'][:500]}\nОтправил: {e['final'][:500]}" for e in examples
            )
        if samples:
            user += "\n\n" + _samples(samples)
        if avoid:
            user += _avoid(avoid)
        out: PlainText = await self._parse(self.smart, system, user, PlainText, "draft")
        return out.text

